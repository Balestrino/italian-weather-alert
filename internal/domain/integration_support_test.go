// readMunicipalities uses the attributed national registry already published
// with this repository, selecting the Toscana rows needed by these tests.
func readMunicipalities(t *testing.T) []Municipality {
	t.Helper()
	file, err := os.Open("../../docs/nazionale/registri/comuni-italia.csv")
	if err != nil {
		t.Fatal(err)
	}
	defer file.Close()
	rows, err := csv.NewReader(file).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	if len(rows) == 0 {
		t.Fatal("empty municipality registry")
	}
	result := make([]Municipality, 0, 273)
	for _, row := range rows[1:] {
		if len(row) < 6 {
			t.Fatalf("invalid municipality row: %v", row)
		}
		if row[2] == "09" {
			result = append(result, Municipality{ISTAT: row[0], Name: row[1], Province: row[5], Supported: true})
		}
	}
	if len(result) != 273 {
		t.Fatalf("Toscana municipality count: %d", len(result))
	}
	return result
}
